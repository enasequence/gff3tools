package uk.ac.ebi.embl.gff3tools.validation.provider;

import java.util.Objects;
import java.util.Optional;
import lombok.Getter;
import uk.ac.ebi.embl.api.entry.genomeassembly.AssemblyType;
import uk.ac.ebi.embl.gff3tools.utils.AssemblyTypeValidator;
import uk.ac.ebi.embl.gff3tools.utils.GapOptionsValidator;

/**
 * User-supplied analysis settings made available to fixes and validators via the
 * validation context.
 *
 * <p>All of these are external input: the {@link AnalysisType}, the optional {@link AssemblyType}
 * of a {@link AnalysisType#SEQUENCE_ASSEMBLY}, the minimum gap size, and the optional {@code
 * gap_type} / {@code linkage_evidence} stamped onto gap features generated by {@code
 * GapGenerationFix}. The minimum gap size must always be greater than zero.
 *
 * <p>The gap options are validated here rather than only at the CLI, because this constructor is
 * the single point every value passes through — a programmatic caller therefore cannot install an
 * invalid {@code gap_type} on the context. That matters because generated gap features are added
 * after the FEATURE-level rules have run, so {@code AssemblyGapValidation} never re-checks them.
 */
public final class AnalysisContext {

    /**
     * The analysis type the submission was made under. Where {@code sequencetools} gates a rule on
     * data class, the gff3tools rule gates on the analysis type instead, using this mapping:
     *
     * <pre>
     * Analysis type            Parent analysis type     Data class
     * SEQUENCE_ASSEMBLY        -                        WGS, STD
     * TRANSCRIPTOME_ASSEMBLY   -                        TSA
     * SEQUENCE_FLATFILE        -                        STD
     * DECOUPLED_ANNOTATION     SEQUENCE_ASSEMBLY        WGS, STD
     * DECOUPLED_ANNOTATION     TRANSCRIPTOME_ASSEMBLY   TSA
     * DECOUPLED_ANNOTATION     SEQUENCE_FLATFILE        STD
     * </pre>
     *
     * <p>A rule uses the analysis type, or the parent analysis type when the analysis type is
     * {@code DECOUPLED_ANNOTATION}: a decoupled annotation has the data class of the analysis it
     * annotates.
     *
     * <p>TODO: {@link AnalysisType} has no {@code DECOUPLED_ANNOTATION} yet, and this class has no
     * parent analysis type. Until both exist, a decoupled annotation cannot be represented, and the
     * rules that read this field compare it directly instead of resolving the parent first.
     */
    @Getter
    private final AnalysisType analysisType;

    /**
     * Optional assembly type; {@code null} when not supplied. Only a {@link
     * AnalysisType#SEQUENCE_ASSEMBLY} can carry one.
     */
    private final AssemblyType assemblyType;

    @Getter
    private final int minGapSize;

    /** Optional INSDC gap_type for generated gap features; {@code null} when not supplied. */
    @Getter
    private final String gapType;

    /** Optional INSDC linkage_evidence for generated gap features; {@code null} when not supplied. */
    @Getter
    private final String linkageEvidence;

    /**
     * @param analysisType the analysis type (must not be {@code null})
     * @param minGapSize   the minimum gap size (must be greater than zero)
     * @throws NullPointerException     if {@code analysisType} is {@code null}
     * @throws IllegalArgumentException if {@code minGapSize} is not greater than zero
     */
    public AnalysisContext(AnalysisType analysisType, int minGapSize) {
        this(analysisType, minGapSize, null, null, null);
    }

    /**
     * @param analysisType    the analysis type (must not be {@code null})
     * @param minGapSize      the minimum gap size (must be greater than zero)
     * @param gapType         optional gap_type for generated gaps; blank is treated as not supplied
     * @param linkageEvidence optional linkage_evidence for generated gaps; blank is treated as not
     *                        supplied
     * @throws NullPointerException     if {@code analysisType} is {@code null}
     * @throws IllegalArgumentException if {@code minGapSize} is not greater than zero, or if the
     *                                  gap_type / linkage_evidence combination is not valid INSDC
     */
    public AnalysisContext(AnalysisType analysisType, int minGapSize, String gapType, String linkageEvidence) {
        this(analysisType, minGapSize, gapType, linkageEvidence, null);
    }

    /**
     * @param analysisType    the analysis type (must not be {@code null})
     * @param minGapSize      the minimum gap size (must be greater than zero)
     * @param gapType         optional gap_type for generated gaps; blank is treated as not supplied
     * @param linkageEvidence optional linkage_evidence for generated gaps; blank is treated as not
     *                        supplied
     * @param assemblyType    optional raw assembly type, in either {@link AssemblyType} spelling;
     *                        blank is treated as not supplied
     * @throws NullPointerException     if {@code analysisType} is {@code null}
     * @throws IllegalArgumentException if {@code minGapSize} is not greater than zero, if the
     *                                  gap_type / linkage_evidence combination is not valid INSDC,
     *                                  or if {@code assemblyType} is supplied for an analysis type
     *                                  other than {@link AnalysisType#SEQUENCE_ASSEMBLY} or does
     *                                  not match a known assembly type
     */
    public AnalysisContext(
            AnalysisType analysisType, int minGapSize, String gapType, String linkageEvidence, String assemblyType) {
        this.analysisType = Objects.requireNonNull(analysisType, "analysisType must not be null");
        if (minGapSize <= 0) {
            throw new IllegalArgumentException("minGapSize must be greater than 0, but was " + minGapSize);
        }
        this.minGapSize = minGapSize;

        GapOptionsValidator.validate(gapType, linkageEvidence).ifPresent(message -> {
            throw new IllegalArgumentException(message);
        });

        // Stored in exactly the form GapOptionsValidator just checked: blank becomes null, and
        // gap_type is lower-cased, so a "Within Scaffold" that passed validation cannot be stamped
        // onto a feature as an INSDC value that does not exist.
        this.gapType = GapOptionsValidator.normaliseGapType(gapType);
        this.linkageEvidence = GapOptionsValidator.normaliseLinkageEvidence(linkageEvidence);
        this.assemblyType = AssemblyTypeValidator.parseAndValidate(analysisType, assemblyType)
                .orElse(null);
    }

    /** The assembly type, or empty when none was supplied. */
    public Optional<AssemblyType> getAssemblyType() {
        return Optional.ofNullable(assemblyType);
    }
}
